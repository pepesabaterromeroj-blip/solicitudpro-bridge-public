import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { ProjectRegistry } from '../src/project-registry.js';
import { readProjectGitStatus } from '../src/project-git-status.js';

test('allowlisted Git status returns only counts and leaves staged, unstaged, untracked and HEAD intact', async () => {
  const root = await mkdtemp(path.join(tmpdir(), 'bridge-readonly-'));
  const repo = path.join(root, 'repo');
  const git = (...args: string[]) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8' }).trim();
  execFileSync('git', ['init', '-q', '-b', 'main', repo]);
  git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.test');
  await writeFile(path.join(repo, 'base.txt'), 'base'); git('add', 'base.txt'); git('commit', '-qm', 'base');
  const base = git('rev-parse', 'HEAD');
  git('remote', 'add', 'origin', path.join(root, 'upstream'));
  git('update-ref', 'refs/remotes/origin/main', base);
  git('config', 'branch.main.remote', 'origin'); git('config', 'branch.main.merge', 'refs/heads/main');
  await writeFile(path.join(repo, 'ahead.txt'), 'ahead'); git('add', 'ahead.txt'); git('commit', '-qm', 'ahead');
  const config = path.join(root, 'local.json');
  await writeFile(config, JSON.stringify({ projects: { solicitudpro: { path: repo } } }));
  const registry = await ProjectRegistry.load(config);
  const clean = await readProjectGitStatus(registry, 'solicitudpro', 'class-windows');
  assert.equal(clean.clean, true); assert.deepEqual([clean.staged, clean.unstaged, clean.untracked, clean.ahead, clean.behind], [0, 0, 0, 1, 0]);
  await writeFile(path.join(repo, 'staged.txt'), 'staged'); git('add', 'staged.txt');
  await writeFile(path.join(repo, 'base.txt'), 'changed');
  await writeFile(path.join(repo, 'untracked-secret.txt'), 'SECRET_VALUE_DO_NOT_EXPOSE');
  const before = git('status', '--porcelain=v1', '-uall');
  const head = git('rev-parse', 'HEAD');
  const result = await readProjectGitStatus(registry, 'solicitudpro', 'class-windows');
  assert.deepEqual(result, { project: 'solicitudpro', deviceId: 'class-windows', branch: 'main', head, clean: false, staged: 1, unstaged: 1, untracked: 1, upstream: 'origin/main', ahead: 1, behind: 0 });
  assert.equal(git('status', '--porcelain=v1', '-uall'), before);
  assert.equal(git('rev-parse', 'HEAD'), head);
  assert.equal(await readFile(path.join(repo, 'untracked-secret.txt'), 'utf8'), 'SECRET_VALUE_DO_NOT_EXPOSE');
  assert.equal(JSON.stringify(result).includes(root), false);
  assert.equal(JSON.stringify(result).includes('SECRET_VALUE_DO_NOT_EXPOSE'), false);
  const tree = git('rev-parse', `${base}^{tree}`);
  const remoteCommit = execFileSync('git', ['-C', repo, 'commit-tree', tree, '-p', base], { input: 'remote', encoding: 'utf8' }).trim();
  git('update-ref', 'refs/remotes/origin/main', remoteCommit);
  const diverged = await readProjectGitStatus(registry, 'solicitudpro', 'class-windows');
  assert.equal(diverged.ahead, 1); assert.equal(diverged.behind, 1);
  for (const project of ['other-project', '../../', '/etc', 'C:\\Windows']) await assert.rejects(readProjectGitStatus(registry, project, 'class-windows'));
});
