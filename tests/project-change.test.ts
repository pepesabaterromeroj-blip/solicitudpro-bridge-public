import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { ProjectRegistry } from '../src/project-registry.js';
import { ChangeApprovalStore } from '../src/change-approval.js';
import { ProjectChangeService, checkoutFingerprint } from '../src/project-change.js';

test('prepare is read-only; apply rejects changed HEAD, content, thread, project and dirty target', async () => {
  const base = await mkdtemp(path.join(tmpdir(), 'bridge-change-test-')); const repo = path.join(base, 'repo');
  await mkdir(path.join(repo, 'src'), { recursive: true }); await writeFile(path.join(repo, 'src/app.js'), 'const a=1;\n');
  const git = (...args: string[]) => execFileSync('git', ['-C', repo, ...args], { windowsHide: true, stdio: 'pipe' });
  git('init'); git('add', '.'); git('-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.test', 'commit', '-m', 'fixture');
  const config = path.join(base, 'local.json'); await writeFile(config, JSON.stringify({ projects: { fixture: { path: repo, changeRoots: ['src'] } } }));
  const registry = await ProjectRegistry.load(config); const store = new ChangeApprovalStore(path.join(base, 'approvals'));
  let thread = 'thread-fixture-1'; let files = ['src/app.js']; let plans = 0; const executions: any[] = [];
  const service = new ProjectChangeService(registry, 'fixture-device', store, async () => thread, 'unused', async (_text, execution) => { plans++; executions.push(execution); return { turnId: 'turn-fixture', blockedActions: 0, output: JSON.stringify({ summary: 'Change constant', files, tests: ['syntax'], warnings: [] }) }; });
  const before = await checkoutFingerprint(repo);
  const pending = await service.prepare('fixture', 'Change constant from 1 to 2');
  assert.equal(pending.selectedProfile, 'standard'); assert.equal(pending.requestedReasoning, 'medium');
  assert.equal(executions[0].selectedProfile, 'standard'); assert.equal(executions[0].requestedReasoning, 'medium');
  const waiting = await service.prepare('fixture', 'Change constant from 1 to 2');
  assert.deepEqual(await checkoutFingerprint(repo), before);
  await assert.rejects(service.apply(pending.approvalId));
  const original = await store.get(pending.approvalId);
  await assert.rejects((service as any).approve('00000000-0000-4000-8000-000000000000'));
  const other = new ProjectChangeService(registry, 'other-device', store, async () => thread, 'unused');
  await assert.rejects((other as any).approve(pending.approvalId));
  await (service as any).approve(pending.approvalId);
  const approved = await store.get(pending.approvalId);
  assert.deepEqual(approved, { ...original, humanApproved: true }, 'APPROVE changes only approval flag');
  await writeFile(path.join(repo, 'src/other.js'), 'const b=2;');
  await assert.rejects(service.approve(waiting.approvalId), /Checkout changed/);
  await assert.rejects(service.apply(pending.approvalId));
  await assert.rejects((service as any).approve(pending.approvalId));
  const dirty1 = await checkoutFingerprint(repo); await writeFile(path.join(repo, 'src/other.js'), 'const b=3;');
  const dirty2 = await checkoutFingerprint(repo); assert.equal(dirty1.status, dirty2.status); assert.notEqual(dirty1.fingerprint, dirty2.fingerprint);
  assert.equal(await readFile(path.join(repo, 'src/app.js'), 'utf8'), 'const a=1;\n');
  git('add', '.'); git('-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.test', 'commit', '-m', 'new-head');
  await assert.rejects(service.approve(waiting.approvalId), /Checkout changed/);
  await assert.rejects(service.apply(pending.approvalId));
  const next = await service.prepare('fixture', 'Change constant from 1 to 2');
  thread = 'thread-fixture-2'; await assert.rejects(service.approve(next.approvalId)); thread = 'thread-fixture-1';
  await service.approve(next.approvalId);
  thread = 'thread-fixture-2'; await assert.rejects(service.apply(next.approvalId)); thread = 'thread-fixture-1';
  await writeFile(path.join(repo, 'src/app.js'), 'const a=3;');
  await assert.rejects(service.prepare('fixture', 'Change constant from 3 to 4'));
  files = ['../outside.js']; await assert.rejects(service.prepare('fixture', 'Change outside fixture file'));
  files = ['src/app.js']; const calls = plans;
  await assert.rejects(service.prepare('unknown', 'Change constant safely'));
  await assert.rejects(service.prepare('fixture', 'git commit all the changes'));
  await assert.rejects(service.prepare('fixture', 'git push to origin main'));
  assert.equal(plans, calls);
});

test('explicit deep PREPARE binds the approved profile and reasoning into the signed plan', async () => {
  const base = await mkdtemp(path.join(tmpdir(), 'bridge-change-profile-')); const repo = path.join(base, 'repo');
  await mkdir(path.join(repo, 'src'), { recursive: true }); await writeFile(path.join(repo, 'src/app.js'), 'const a=1;\n');
  const git = (...args: string[]) => execFileSync('git', ['-C', repo, ...args], { windowsHide: true, stdio: 'pipe' });
  git('init'); git('add', '.'); git('-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.test', 'commit', '-m', 'fixture');
  const config = path.join(base, 'local.json'); await writeFile(config, JSON.stringify({ projects: { fixture: { path: repo, changeRoots: ['src'] } } }));
  const registry = await ProjectRegistry.load(config); const store = new ChangeApprovalStore(path.join(base, 'approvals'));
  let execution: any;
  const service = new ProjectChangeService(registry, 'fixture-device', store, async () => 'thread-fixture-1', 'unused', async (_text, selected) => {
    execution = selected; return { turnId: 'turn-fixture', blockedActions: 0, output: JSON.stringify({ summary: 'Safe change', files: ['src/app.js'], tests: ['syntax'], warnings: [] }) };
  });
  const pending = await service.prepare('fixture', 'Review and plan this security-sensitive change', { profile: 'deep' });
  const stored = await store.get(pending.approvalId);
  assert.equal(execution.selectedProfile, 'deep'); assert.equal(execution.requestedReasoning, 'high');
  assert.equal(stored.selectedProfile, 'deep'); assert.equal(stored.requestedReasoning, 'high');
  assert.equal(pending.selectedProfile, 'deep');
});
